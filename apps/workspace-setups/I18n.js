function resolve(setting, localeName) {
  var value = String(setting || "auto")
  if (value === "en" || value === "de") return value
  return String(localeName || "").toLowerCase().indexOf("de") === 0 ? "de" : "en"
}

function tr(language, key, args) {
  var table = strings[language] || strings.en
  var text = table[key] !== undefined ? table[key] : (strings.en[key] !== undefined ? strings.en[key] : key)
  if (args) for (var name in args) text = text.split("{" + name + "}").join(String(args[name]))
  return text
}
